#!/usr/bin/env node
// Builds index.html and sitemap.xml from build/template.html + build/tools.json.
//
//   node build/build.mjs           write index.html and sitemap.xml
//   node build/build.mjs --check   exit 1 if index.html is out of date
//
// To add a tool: add an entry to the right category in tools.json (all six
// languages), run the build, commit index.html + sitemap.xml + tools.json.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const SITE = 'https://www.robbiemed.org/';
const LANGS = ['ko', 'en', 'fr', 'zh', 'ru', 'ar'];
const DEFAULT = 'ko';

const data = JSON.parse(readFileSync(join(HERE, 'tools.json'), 'utf8'));
const template = readFileSync(join(HERE, 'template.html'), 'utf8');

/* ---------- validate ---------- */
const problems = [];
const seen = new Set();
for (const c of data.categories) {
  for (const f of ['name', 'short']) for (const l of LANGS)
    if (!c[f]?.[l]) problems.push(`category ${c.key}: missing ${f}.${l}`);
  for (const t of c.tools) {
    if (seen.has(t.key)) problems.push(`duplicate tool key: ${t.key}`);
    seen.add(t.key);
    if (!/^[a-z0-9]+$/.test(t.key)) problems.push(`${t.key}: key must be [a-z0-9]`);
    if (!/^https:\/\//.test(t.url || '')) problems.push(`${t.key}: url must be https`);
    if (!t.name) problems.push(`${t.key}: missing name`);
    for (const l of LANGS) if (!t.d?.[l]) problems.push(`${t.key}: missing d.${l}`);
  }
}
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

/* ---------- helpers ---------- */
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
// safe to drop inside <script>: no "</script>", no line-separator surprises
const LS = String.fromCharCode(0x2028), PS = String.fromCharCode(0x2029);
const jsonForScript = v => JSON.stringify(v).replace(/</g, '\\u003c').split(LS).join('\\u2028').split(PS).join('\\u2029');
const fill = (src, marker, value) => {
  if (!src.includes(marker)) throw new Error('template is missing ' + marker);
  return src.replace(marker, () => value);
};

/* ---------- generated fragments ---------- */
const nav = [
  ...data.categories.map(c => `    <a href="#s-${c.key}" data-n="${c.key}">${esc(c.short[DEFAULT])}</a>`),
  `    <a href="#contact" data-t="cat.contact">연락처</a>`
].join('\n');

const sections = data.categories.map(c => [
  `<section class="cat" id="s-${c.key}" data-cat>`,
  `  <h2><span data-t="cat.${c.key}">${esc(c.name[DEFAULT])}</span><span class="cat-count">· ${c.tools.length}</span></h2>`,
  `  <ul>`,
  ...c.tools.map(t =>
    `    <li class="tool" data-k="${t.key}" data-s="${esc(t.tags || t.key)}"><a href="${esc(t.url)}" target="_blank" rel="noopener">${esc(t.name)}</a> <span class="desc">${esc(t.d[DEFAULT])}</span></li>`),
  `  </ul>`,
  `</section>`
].join('\n')).join('\n\n');

const toolTr = Object.fromEntries(LANGS.map(l => [l, {
  cat: Object.fromEntries(data.categories.map(c => [c.key, c.name[l]])),
  short: Object.fromEntries(data.categories.map(c => [c.key, c.short[l]])),
  d: Object.fromEntries(data.categories.flatMap(c => c.tools.map(t => [t.key, t.d[l]])))
}]));

const tools = data.categories.flatMap(c => c.tools);
const ld = {
  '@context': 'https://schema.org',
  '@graph': [
    { '@type': 'WebSite', '@id': SITE + '#website', url: SITE, name: 'robbie.med',
      description: 'Free, open, privacy-respecting clinical tools, calculators and simulators.',
      inLanguage: LANGS, author: { '@id': SITE + '#person' } },
    { '@type': 'Person', '@id': SITE + '#person', name: 'robbie.med', url: SITE,
      email: 'mailto:talk@robbiemed.org',
      sameAs: ['https://github.com/robbie-med', 'https://mastodon.social/@robbiemed'] },
    { '@type': 'ItemList', '@id': SITE + '#tools', name: 'Tools', numberOfItems: tools.length,
      itemListElement: tools.map((t, i) => ({
        '@type': 'ListItem', position: i + 1,
        item: {
          '@type': 'SoftwareApplication', name: t.name, url: t.url, description: t.d.en,
          applicationCategory: 'HealthApplication',
          operatingSystem: t.os || 'Any (web browser)',
          isAccessibleForFree: true,
          offers: { '@type': 'Offer', price: '0', priceCurrency: 'USD' }
        }
      })) }
  ]
};

let html = template;
html = fill(html, '<!-- @JSONLD -->',
  '<script type="application/ld+json">\n' + JSON.stringify(ld, null, 2).replace(/</g, '\\u003c') + '\n</script>');
html = fill(html, '<!-- @NAV -->', nav);
html = fill(html, '<!-- @SECTIONS -->', sections);
html = fill(html, '/* @TOOL_TR */', 'var TOOL_TR = ' + jsonForScript(toolTr) + ';');
html = html.replace('<!DOCTYPE html>\n',
  '<!DOCTYPE html>\n<!-- Generated by build/build.mjs from build/template.html and build/tools.json. Edit those, not this file. -->\n');

const out = join(ROOT, 'index.html');
if (process.argv.includes('--check')) {
  const current = readFileSync(out, 'utf8');
  if (current !== html) { console.error('index.html is out of date: run node build/build.mjs'); process.exit(1); }
  console.log('index.html is up to date (' + tools.length + ' tools)');
  process.exit(0);
}
writeFileSync(out, html);

const today = new Date().toISOString().slice(0, 10);
writeFileSync(join(ROOT, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:xhtml="http://www.w3.org/1999/xhtml">
  <url>
    <loc>${SITE}</loc>
    <lastmod>${today}</lastmod>
    <priority>1.0</priority>
${LANGS.map(l => `    <xhtml:link rel="alternate" hreflang="${l}" href="${SITE}?lang=${l}"/>`).join('\n')}
  </url>
${tools.map(t => `  <url>
    <loc>${esc(t.url)}/</loc>
    <priority>0.8</priority>
  </url>`).join('\n')}
</urlset>
`);
console.log('built index.html and sitemap.xml: ' + data.categories.length + ' sections, ' + tools.length + ' tools');
